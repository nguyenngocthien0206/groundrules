"""Generate governance/registry.md: every metric and action, its owner and its status.

Usage: python governance/registry.py   (or `make registry`)

The page a manager reads. It is generated from the dbt manifest, so it can
never disagree with the definitions; the lint fails when it is out of date.
It shows the date each metric is due for recertification rather than
"stale", so the file does not change with the calendar.
"""

import sys
from collections import Counter
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from repo import ROOT, Repo, governed, load  # noqa: E402

REGISTRY = ROOT / "governance" / "registry.md"
STATUS_ORDER = {"certified": 0, "deprecated": 1, "draft": 2}


def _due(meta: dict) -> str:
    try:
        return str(date.fromisoformat(str(meta["certified_on"])) + timedelta(days=int(meta["recertify_every_days"])))
    except (KeyError, ValueError):
        return "?"


def render(repo: Repo) -> str:
    questions = Counter(q["metric"] for q in repo.questions)
    metrics = sorted(
        governed(repo).values(),
        key=lambda m: (STATUS_ORDER.get(m.meta.get("status"), 9), m.group or "", m.name),
    )
    lines = [
        "# Metric registry\n",
        "\n",
        "Generated by `make registry` from the dbt manifest. Do not edit by hand.\n",
        "\n",
        "Every metric people and agents may use, who owns it, and the record that\n",
        "explains it. Certified metrics are the only ones to answer with; a\n",
        "deprecated one points to its replacement.\n",
        "\n",
        "## Metrics\n",
        "\n",
        "| Metric | Label | Owner | Version | Status | Certified on | Recertify by | Decision | Golden questions | Replaced by |\n",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n",
    ]
    for m in metrics:
        meta = m.meta
        decision = meta.get("decision") or ""
        decision_link = f"[{Path(decision).stem}](../{decision})" if decision else "-"
        team = repo.group_teams.get(m.group or "") or ""
        lines.append(
            f"| `{m.name}` | {m.label} | {m.group} ({team}) | {meta.get('version', '?')} | {meta.get('status', '?')} "
            f"| {meta.get('certified_on', '?')} | {_due(meta)} | {decision_link} | {questions.get(m.name, 0)} "
            f"| {meta.get('replaced_by') or '-'} |\n"
        )
    hidden = sum(1 for m in repo.metrics.values() if m.hidden)
    lines += [
        "\n",
        f"{hidden} building-block metrics are hidden: they feed the metrics above and are not answered with directly.\n",
        "\n",
        "## Actions\n",
        "\n",
        "What an agent may propose. A person in the approver group signs off each\n",
        "proposal before anything is written.\n",
        "\n",
        "| Action | Label | Owner | Approver | Version | Status | Decision | Reads | Golden questions |\n",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n",
    ]
    for name, action in sorted(repo.actions.items()):
        spec = action["spec"] or {}
        decision = spec.get("decision") or ""
        decision_link = f"[{Path(decision).stem}](../{decision})" if decision else "-"
        reads = ", ".join(f"`{m}` v{v}" for m, v in sorted(((spec.get("reads") or {}).get("metrics") or {}).items()))
        owner, approver = spec.get("owner"), spec.get("approver")
        lines.append(
            f"| `{name}` | {spec.get('label', '?')} | {owner} ({repo.group_teams.get(owner or '') or ''}) "
            f"| {approver} ({repo.group_teams.get(approver or '') or ''}) | {spec.get('version', '?')} "
            f"| {spec.get('status', '?')} | {decision_link} | {reads or '-'} "
            f"| {sum(1 for q in repo.action_questions if q.get('action') == name)} |\n"
        )
    lines += [
        "\n",
        "## What reads the data\n",
        "\n",
        "| Exposure | Type | Maturity | Owner | Reads | Moving to |\n",
        "| --- | --- | --- | --- | --- | --- |\n",
    ]
    for name, e in sorted(repo.exposures.items()):
        lines.append(
            f"| `{name}` ({e['label']}) | {e['type']} | {e['maturity']} | {e['owner']} "
            f"| {', '.join(e['depends_on'])} | {e['replaced_by_metric'] or '-'} |\n"
        )
    return "".join(lines)


def main() -> int:
    REGISTRY.write_text(render(load(with_text_files=False)), encoding="utf-8", newline="\n")
    print(f"Wrote {REGISTRY.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
